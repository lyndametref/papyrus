fn document_page_renderer(renderer: Option<&str>) -> bool {
    matches!(
        renderer,
        Some(
            "list_page"
                | "view_page"
                | "edit_page"
                | "edit_page_glossary"
                | "edit_page_ui_spec"
                | "edit_page_ui_mockup"
                | "edit_page_business_rule"
                | "edit_page_audit_record"
                | "edit_page_tech_spec"
                | "edit_page_use_case"
                | "document_detail_page"
                | "document_edit_page"
                | "document_conflict_page"
                | "document_not_found_page"
        )
    )
}

fn git_show(root: &std::path::Path, path: &str) -> Option<String> {
    let manifest = std::path::Path::new(env!("CARGO_MANIFEST_DIR"));
    let output = std::process::Command::new("git")
        .current_dir(manifest)
        .args(["show", &format!("{BASELINE_COMMIT}:{path}")])
        .output()
        .ok()?;
    if !output.status.success() {
        return None;
    }
    let _ = root;
    Some(String::from_utf8_lossy(&output.stdout).to_string())
}

fn selector_applies(renderer: Option<&str>, selector: &str) -> bool {
    match selector {
        "main.main" | "div.error-page" => renderer == Some("document_not_found_page"),
        "form.form" => matches!(
            renderer,
            Some(
                "edit_page"
                    | "edit_page_glossary"
                    | "edit_page_ui_spec"
                    | "edit_page_ui_mockup"
                    | "edit_page_business_rule"
                    | "edit_page_audit_record"
                    | "edit_page_tech_spec"
                    | "edit_page_use_case"
                    | "document_edit_page"
                    | "document_conflict_page"
            )
        ),
        "section.section" => renderer == Some("list_page"),
        "p.text" => matches!(renderer, Some("view_page" | "document_detail_page")),
        _ => true,
    }
}

fn baseline_allowlist(
    case: &str,
    renderer: Option<&str>,
    expected: &str,
    actual: &str,
) -> semantic_html::Allowlist {
    let mut entries: Vec<semantic_html::AllowedDelta> = BASELINE_SELECTORS
        .iter()
        .filter(|(selector, _, _)| {
            selector_applies(renderer, selector)
                && (semantic_html::selector_differs(expected, actual, selector)
                    || (*selector == "p.text"
                        && semantic_html::selector_differs(
                            expected,
                            actual,
                            "section.record-section",
                        )))
        })
        .map(|(selector, reason, delta)| semantic_html::AllowedDelta {
            case: Box::leak(case.to_string().into_boxed_str()),
            selector,
            reason: *reason,
            delta,
        })
        .collect();
    // Drop any entry that is not necessary for the union to hide every
    // difference. This keeps the allowlist per case and per selector.
    loop {
        let mut removed = false;
        let mut index = 0;
        while index < entries.len() {
            let without: Vec<&str> = entries
                .iter()
                .enumerate()
                .filter(|(other, _)| *other != index)
                .map(|(_, entry)| entry.selector)
                .collect();
            if semantic_html::equal_after_filter(expected, actual, &without) {
                entries.remove(index);
                removed = true;
            } else {
                index += 1;
            }
        }
        if !removed {
            break;
        }
    }
    semantic_html::Allowlist::new(entries)
}

#[test]
fn every_document_page_matches_the_pre_ms035_baseline_semantically() {
    let root = corpus_root();
    let manifest = load_manifest(&root);
    let mut compared = 0usize;
    let mut allowed = 0usize;
    let mut breakdown: std::collections::BTreeMap<(&str, &str), usize> =
        std::collections::BTreeMap::new();
    for case in &manifest.cases {
        if !case
            .artifacts
            .iter()
            .any(|artifact| artifact == "page.html")
            || !document_page_renderer(case.renderer.as_deref())
        {
            continue;
        }
        let relative = format!(
            "tests/fixtures/characterization/corpus/expected/{}/page.html",
            case.id
        );
        let baseline = git_show(&root, &relative)
            .unwrap_or_else(|| panic!("{}: missing baseline at {BASELINE_COMMIT}", case.id));
        let actual = fs::read_to_string(root.join("expected").join(&case.id).join("page.html"))
            .unwrap_or_else(|error| panic!("{}: read accepted page: {error}", case.id));
        let allowlist = baseline_allowlist(&case.id, case.renderer.as_deref(), &baseline, &actual);
        allowed += allowlist.len();
        for entry in allowlist.entries() {
            *breakdown
                .entry((entry.selector, entry.reason.code()))
                .or_default() += 1;
        }
        semantic_html::compare_document_html(&case.id, &baseline, &actual, &allowlist)
            .unwrap_or_else(|error| panic!("{error}"));
        compared += 1;
    }
    assert!(compared > 0, "the corpus declares document HTML pages");
    eprintln!("semantic baseline: {compared} document pages compared, {allowed} allowed deltas");
    eprintln!("allowed deltas by selector/reason: {breakdown:?}");
}
