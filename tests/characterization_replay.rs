#[path = "support/semantic_html.rs"]
mod semantic_html;

use std::collections::BTreeMap;
use std::fs;
use std::path::PathBuf;

use characterization::{
    Case, Ctx, Runner, compare_case, corpus_root, is_document_page_renderer, load_manifest,
};
use semantic_html::{Allowlist, compare_document_html};

fn minimal_case(id: &str, artifacts: &[&str]) -> Case {
    Case {
        id: id.to_string(),
        kind: "http".to_string(),
        argv: Vec::new(),
        request: None,
        document_type: None,
        model: None,
        renderer: None,
        record: None,
        project: None,
        artifacts: artifacts.iter().map(|name| (*name).to_string()).collect(),
    }
}

fn replay(kind: &'static str, tag: &str) {
    let root = corpus_root();
    let manifest = load_manifest(&root);
    assert_eq!(manifest.schema, "papyrus.characterization-cases/1");
    assert!(
        manifest.unreachable.is_empty(),
        "every declared renderer must now have a call site (TASK-267)"
    );
    assert!(
        manifest.cases.iter().any(|case| case.kind == kind),
        "the manifest declares {kind} cases"
    );
    let ctx = Ctx::new(tag);
    Runner {
        root,
        ctx: &ctx,
        write: false,
        only: Some(kind),
    }
    .run();
}

