//! TASK-240 / MS-032 AC-5, AC-13: replay the characterization corpus.
//!
//! Part of the default `cargo test` run. Every case from `cases.json` runs
//! against a throwaway copy of the committed seed project. Record files, JSON
//! payloads, status codes, and non-document HTML are compared exactly; document
//! HTML is compared semantically (TC-184) with no allowance.

#[path = "support/characterization.rs"]
