#[test]
fn a_single_byte_change_fails_the_comparison() {
    let scratch = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join(".tmp")
        .join(format!("characterization-negative-{}", std::process::id()));
    let _ = fs::remove_dir_all(&scratch);
    fs::create_dir_all(&scratch).expect("create negative workspace");

    let mut observed: BTreeMap<String, Vec<u8>> = BTreeMap::new();
    observed.insert("page.html".to_string(), b"<h1>Stable</h1>\n".to_vec());
    let case = minimal_case("http/negative", &["page.html"]);
    fs::write(scratch.join("page.html"), b"<h1>Stable</h1>\n").expect("write baseline");
    assert!(
        compare_case(&scratch, &observed, &case).is_ok(),
        "the unchanged artifact must compare equal"
    );

    fs::write(scratch.join("page.html"), b"<h1>Stabke</h1>\n").expect("write one-byte change");
    let error = compare_case(&scratch, &observed, &case)
        .expect_err("a one-byte change must fail the comparison");
    assert!(
        error.contains("page.html"),
        "the failure names the artifact"
    );

    fs::write(scratch.join("page.html"), b"<h1>Stable</h1>\n").expect("restore baseline");
    fs::write(scratch.join("extra.txt"), b"extra").expect("write extra artifact");
    assert!(
        compare_case(&scratch, &observed, &case).is_err(),
        "an extra expected artifact must fail the comparison"
    );
    let _ = fs::remove_dir_all(&scratch);
}

// TASK-269: the pre-MS-035 baseline lives at commit 214a252. The committed
// corpus was regenerated by TASK-265..268, so compare the accepted pages
// against that frozen baseline semantically, with the static node allowlist in
// tests/fixtures/characterization/semantic-allowlist.json. Every allowance is
// per case and per node part; no page container is allowed (AUD-145 H1).
const BASELINE_COMMIT: &str = "214a252";

fn git_show(root: &std::path::Path, path: &str) -> Option<String> {
    let manifest = std::path::Path::new(env!("CARGO_MANIFEST_DIR"));
    let output = std::process::Command::new("git")
        .current_dir(manifest)
        .args(["show", &format!("{BASELINE_COMMIT}:{path}")])
        .output()
        .ok()?;
    if !output.status.success() {
        return None;
    }
    let _ = root;
    Some(String::from_utf8_lossy(&output.stdout).to_string())
}

fn document_pages() -> Vec<(String, String, String)> {
    let root = corpus_root();
    let manifest = load_manifest(&root);
    let mut pages = Vec::new();
    for case in &manifest.cases {
        if !case
            .artifacts
            .iter()
            .any(|artifact| artifact == "page.html")
            || !is_document_page_renderer(case.renderer.as_deref())
        {
            continue;
        }
        let relative = format!(
            "tests/fixtures/characterization/corpus/expected/{}/page.html",
            case.id
        );
        let baseline = git_show(&root, &relative)
            .unwrap_or_else(|| panic!("{}: missing baseline at {BASELINE_COMMIT}", case.id));
        let actual = fs::read_to_string(root.join("expected").join(&case.id).join("page.html"))
            .unwrap_or_else(|error| panic!("{}: read accepted page: {error}", case.id));
        pages.push((case.id.clone(), baseline, actual));
    }
    pages
}

#[test]
fn every_document_page_matches_the_pre_ms035_baseline_semantically() {
    let allowlist = Allowlist::static_table();
    let mut compared = 0usize;
    for (case, baseline, actual) in document_pages() {
        compare_document_html(&case, &baseline, &actual, allowlist)
            .unwrap_or_else(|error| panic!("{error}"));
        compared += 1;
    }
    assert!(compared > 0, "the corpus declares document HTML pages");
    eprintln!(
        "semantic baseline: {compared} document pages, {} node allowances",
        allowlist.len()
    );
}

#[test]
fn static_allowlist_entries_are_documented_node_parts() {
    let deltas = fs::read_to_string(corpus_root().join("EXPECTED-DELTAS.md"))
        .expect("read EXPECTED-DELTAS.md");
    for entry in Allowlist::static_table().entries() {
        assert!(
            entry.is_documented(&deltas),
            "{}: undocumented allowance {} / {} at {:?}",
            entry.case,
            entry.reason,
            entry.delta,
            entry.expected.as_deref().or(entry.actual.as_deref())
        );
        assert!(
            entry.expected.is_some() || entry.actual.is_some(),
            "{}: allowance names no node",
            entry.case
        );
    }
}

#[test]
fn static_allowlist_has_no_page_container_entry() {
    let pages: BTreeMap<String, (String, String)> = document_pages()
        .into_iter()
        .map(|(case, baseline, actual)| (case, (baseline, actual)))
        .collect();
    for entry in Allowlist::static_table().entries() {
        let (baseline, actual) = pages.get(&entry.case).expect("allowlist case page");
        if let Some(path) = entry.expected.as_deref()
            && let Some(tag) = semantic_html::element_tag_at_path(baseline, path)
        {
            assert!(
                !is_page_container(&tag, entry.kind),
                "{}: allowance targets the {tag} container at {path}",
                entry.case
            );
        }
        if let Some(path) = entry.actual.as_deref()
            && let Some(tag) = semantic_html::element_tag_at_path(actual, path)
        {
            assert!(
                !is_page_container(&tag, entry.kind),
                "{}: allowance targets the {tag} container at {path}",
                entry.case
            );
        }
    }
}

fn is_page_container(tag: &str, kind: semantic_html::AllowKind) -> bool {
    // An element entry allows only the node's own start/end tokens; a subtree
    // entry would hide the container's whole content and is forbidden.
    matches!(tag, "form" | "main" | "section") && kind == semantic_html::AllowKind::Subtree
}

#[test]
fn each_page_kind_fails_a_single_label_text_field_or_link_mutation() {
    let allowlist = Allowlist::static_table();
    let mutations: &[(&str, &str, &str)] = &[
        ("http/list-req", ">Backlog<", ">Backlog changed<"),
        (
            "http/list-req",
            ">Requirement group one<",
            ">Requirement group one changed<",
        ),
        (
            "http/list-req",
            "data-column=\"title\"",
            "data-column=\"title-changed\"",
        ),
        (
            "http/list-req",
            "href=\"/?type=task\"",
            "href=\"/?type=task-changed\"",
        ),
        ("http/view-req", ">Backlog<", ">Backlog changed<"),
        ("http/view-req", ">User story<", ">User story changed<"),
        (
            "http/view-req",
            "class=\"record-section\"",
            "class=\"record-section-changed\"",
        ),
        (
            "http/view-req",
            "href=\"/?type=task\"",
            "href=\"/?type=task-changed\"",
        ),
        ("http/edit-req", ">Backlog<", ">Backlog changed<"),
        (
            "http/edit-req",
            "value=\"Resolved dependency\"",
            "value=\"Changed dependency\"",
        ),
        ("http/edit-req", "name=\"title\"", "name=\"title-changed\""),
        (
            "http/edit-req",
            "href=\"/?type=task\"",
            "href=\"/?type=task-changed\"",
        ),
        ("http/conflict-req", ">Backlog<", ">Backlog changed<"),
        (
            "http/conflict-req",
            ">Document types<",
            ">Document types changed<",
        ),
        (
            "http/conflict-req",
            "aria-label=\"Document types\"",
            "aria-label=\"Document types changed\"",
        ),
        (
            "http/conflict-req",
            "href=\"/?type=task\"",
            "href=\"/?type=task-changed\"",
        ),
        ("http/not-found-req", ">Backlog<", ">Backlog changed<"),
        (
            "http/not-found-req",
            "The requested record was not found.",
            "The requested record was not found here.",
        ),
        (
            "http/not-found-req",
            "aria-label=\"Document types\"",
            "aria-label=\"Document types changed\"",
        ),
        (
            "http/not-found-req",
            "href=\"/?type=task\"",
            "href=\"/?type=task-changed\"",
        ),
    ];
    let pages: BTreeMap<String, (String, String)> = document_pages()
        .into_iter()
        .map(|(case, baseline, actual)| (case, (baseline, actual)))
        .collect();
    for (case, from, to) in mutations {
        let (baseline, actual) = pages.get(*case).expect("mutation case page");
        assert!(
            actual.contains(from),
            "{case}: mutation source is absent: {from}"
        );
        let mutated = actual.replacen(from, to, 1);
        assert!(
            compare_document_html(case, baseline, &mutated, allowlist).is_err(),
            "{case}: a single-node mutation was accepted: {from} -> {to}"
        );
    }
}

#[test]
fn tc184_document_pages_contain_no_per_type_wrapper_element() {
    let wrappers = [
        "req-page",
        "nfr-page",
        "glossary-page",
        "rule-page",
        "audit-page",
        "tech-spec-page",
        "use-case-page",
        "test-case-page",
        "test-report-page",
        "ui-spec-page",
        "ui-mockup-page",
        "note-page",
    ];
    for (case, _, actual) in document_pages() {
        for wrapper in wrappers {
            assert!(
                !actual.contains(wrapper),
                "{case}: per-type wrapper element {wrapper} remains"
            );
        }
        assert!(
            actual.contains("<main class=\"main\">"),
            "{case}: every document page uses the one main element"
        );
    }
}
